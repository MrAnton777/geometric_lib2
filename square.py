
def area(a):
    """
    Вычисляет площадь квадрата по длине стороны a.
    Параметры:
    a - длина стороны квадрата.

    Вывод: площадь квадрата.
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине стороны a.

    Параметры:
    a - длина стороны квадрата.

    Вывод: периметр квадрата.
    """
    return 4 * a
