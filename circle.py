import math


def area(r):

    """
    Вычисляет площадь круга по радиусу r.

    Параметры:
    r - радиус круга.

    Вывод: площадь круга.


    """

    return math.pi * r * r


def perimeter(r):

    """ 
    Вычисляет периметр круга по радиусу r.

    Параметры:
    r - радиус круга.

    Вывод: периметр круга.

    """
    return 2 * math.pi * r

